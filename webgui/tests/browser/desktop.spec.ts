import { expect, test } from '@playwright/test';
test('desktop lifecycle, keyboard, geometry, persistence and no external traffic', async ({ page }) => {
  const external: string[] = [];
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:4173/')) external.push(r.url()); });
  await page.goto('/');
  await expect(page.locator('.mode-banner')).toContainText('DEMO');
  const status = page.getByRole('dialog', { name: 'System Status', exact: true });
  await expect(status).toContainText('UNKNOWN');
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.getByRole('menuitem', { name: 'ECU Library', exact: true }).click();
  const ecu = page.getByRole('dialog', { name: 'ECU Library', exact: true });
  await expect(ecu).toBeVisible();
  await expect(ecu.getByRole('button', { name: 'Open reference editor' })).toBeDisabled();
  const before = await ecu.boundingBox();
  await ecu.getByLabel('Move ECU Library with arrow keys').focus();
  await page.keyboard.press('ArrowRight');
  expect((await ecu.boundingBox())!.x).toBe(before!.x + 8);
  await ecu.getByLabel('Resize ECU Library with arrow keys').focus();
  await page.keyboard.press('ArrowRight');
  expect((await ecu.boundingBox())!.width).toBe(before!.width + 8);
  await ecu.getByRole('button', { name: 'Maximize ECU Library', exact: true }).click();
  expect((await ecu.boundingBox())!.width).toBe(1280);
  await ecu.getByRole('button', { name: 'Restore ECU Library', exact: true }).click();
  expect((await ecu.boundingBox())!.width).toBe(before!.width + 8);
  await ecu.getByRole('button', { name: 'Minimize ECU Library', exact: true }).click();
  await expect(ecu).toBeHidden();
  await page.locator('.task-buttons').getByRole('button', { name: 'ECU Library' }).click();
  await page.reload(); await expect(ecu).toBeVisible();
  await page.setViewportSize({ width: 360, height: 640 });
  const box = (await ecu.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(360);
  await ecu.getByRole('button', { name: 'Close ECU Library', exact: true }).click();
  await expect(ecu).toHaveCount(0);
  expect(external).toEqual([]);
});
test('real mode stays unavailable, corrupt layout and blocked storage recover', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('vision.desktop.layout.v1', '{corrupt'));
  await page.goto('/?mode=real');
  await expect(page.locator('.mode-banner')).toContainText('UNAVAILABLE');
  await expect(page.getByRole('dialog')).toContainText('Real adapter unavailable');
  await expect(page.getByRole('dialog')).not.toContainText('Synthetic');
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw Error('disabled'); }; });
  await page.reload();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeFocused();
});
test('pointer dragging/resizing, stacking and layout reset', async ({ page }) => {
  await page.goto('/');
  const status = page.getByRole('dialog', { name: 'System Status', exact: true });
  const original = (await status.boundingBox())!;
  const title = status.getByLabel('Move System Status with arrow keys');
  const titleBox = (await title.boundingBox())!;
  await page.mouse.move(titleBox.x + 100, titleBox.y + 10);
  await page.mouse.down(); await page.mouse.move(titleBox.x + 145, titleBox.y + 40); await page.mouse.up();
  const moved = (await status.boundingBox())!;
  expect(moved.x).toBe(original.x + 45); expect(moved.y).toBe(original.y + 30);
  const handle = (await status.getByLabel('Resize System Status with arrow keys').boundingBox())!;
  await page.mouse.move(handle.x + 8, handle.y + 8);
  await page.mouse.down(); await page.mouse.move(handle.x + 48, handle.y + 38); await page.mouse.up();
  expect((await status.boundingBox())!.width).toBe(original.width + 40);
  await page.locator('.desktop-icons').getByRole('button', { name: 'Control Panel', exact: true }).click();
  const control = page.getByRole('dialog', { name: 'Control Panel', exact: true });
  await expect(control).toHaveClass(/active/);
  await control.getByRole('button', { name: 'Reset window layout' }).click();
  await expect(control).toHaveCount(0);
  expect((await status.boundingBox())!.x).toBe(original.x);
  await page.screenshot({ path: 'test-results/desktop.png' });
});

test('default desktop keeps icons unobstructed and full system report visible at 1280×800', async ({ page }) => {
  await page.goto('/');
  const status = page.getByRole('dialog', { name: 'System Status', exact: true });
  await expect(status).toContainText('Sony Camera');
  const icons = (await page.locator('.desktop-icons').boundingBox())!;
  const window = (await status.boundingBox())!;
  expect(window.x).toBeGreaterThanOrEqual(icons.x + icons.width);
  const body = status.locator('.window-body');
  expect(await body.evaluate(el => el.scrollHeight <= el.clientHeight)).toBe(true);
  await page.screenshot({ path: 'test-results/audit-desktop.png' });
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await expect(page.getByRole('menu')).toBeVisible();
  await page.screenshot({ path: 'test-results/audit-start.png' });
  await page.getByRole('menuitem', { name: 'ECU Library', exact: true }).click();
  const ecu = page.getByRole('dialog', { name: 'ECU Library', exact: true });
  await expect(ecu).toBeVisible();
  await expect(status).toBeVisible();
  await expect(ecu).toHaveClass(/active/);
  await page.screenshot({ path: 'test-results/audit-multiple.png' });
});
