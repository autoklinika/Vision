import {expect,test} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('simplified ECU editor saves declared data, photographs and revisions without execution parameters',async({page})=>{
  test.setTimeout(120000);
  const credentials=JSON.parse(readFileSync('../.station-test-auth.json','utf8'));
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('User name',{exact:true}).fill(credentials.username);
  await page.getByLabel('Password',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.getByRole('dialog',{name:'Navigation',exact:true}).getByRole('button',{name:'ECU Library',exact:true}).click();
  const library=page.locator('[data-module="ecu"]');
  await library.getByRole('button',{name:'New profile',exact:true}).click();
  const editor=library.getByRole('region',{name:'ECU reference editor'});
  const button=(name:string)=>editor.getByRole('button',{name,exact:true});
  const id=editor.getByRole('region',{name:'ECU identification',exact:true});
  const geo=editor.getByRole('region',{name:'ECU geometry',exact:true});
  const photos=editor.getByRole('region',{name:'Reference photographs',exact:true});
  const inspect=editor.getByRole('region',{name:'Inspection preferences',exact:true});
  await expect(editor.locator('.basic-card')).toHaveCount(4);
  await expect(editor.getByLabel('New profile ID',{exact:true})).toHaveCount(0);
  await expect(editor.getByLabel('Revision',{exact:true})).toHaveCount(0);
  await expect(button('Save ECU profile')).toBeDisabled();
  await id.getByRole('textbox',{name:'Manufacturer',exact:true}).fill('Synthetic Manufacturer');
  const family=id.getByRole('textbox',{name:'ECU family',exact:true});
  await family.fill('bad/label');
  await expect(family).toHaveAttribute('aria-invalid','true');
  await expect(id).toContainText('Use letters, digits, spaces');
  await family.fill('Synthetic Truck');
  await id.getByRole('textbox',{name:'Variant',exact:true}).fill('285');
  await id.getByRole('textbox',{name:'Manufacturer part numbers',exact:true}).fill('TEST-PART-1\nTEST-PART-2');
  await id.getByRole('textbox',{name:'OEM part numbers',exact:true}).fill('TEST-OE-285');
  await geo.getByRole('combobox',{name:'Physical state',exact:true}).selectOption('pcb_top');
  await geo.getByRole('button',{name:'Add state',exact:true}).click();
  const x=geo.getByRole('textbox',{name:'Length X (mm)',exact:true});
  await x.fill('0');
  await expect(button('Save ECU profile')).toBeDisabled();
  await expect(x).toHaveAttribute('aria-invalid','true');
  await x.fill('100,25');
  await geo.getByRole('textbox',{name:'Width Y (mm)',exact:true}).fill('80');
  await inspect.getByRole('combobox',{name:'Inspection template',exact:true}).selectOption('standard_pcb');
  await inspect.getByRole('checkbox',{name:'Whole PCB photograph',exact:true}).check();
  await inspect.getByRole('checkbox',{name:'Oblique views',exact:true}).check();
  await inspect.getByRole('textbox',{name:'Special requirements (optional)',exact:true}).fill('Fixture notes\nNot an executable recipe');
  await expect(photos.getByRole('button',{name:'Add photograph',exact:true})).toBeDisabled();
  await button('Save ECU profile').click();
  await expect(editor).toContainText('Profile saved in Core.');
  const readLibrary=async()=>await (await page.request.get('/api/v1/library')).json();
  const station=await (await page.request.get('/api/v1/station')).json();
  const headers={Origin:'http://127.0.0.1:18492','X-Vision-Client':'webgui'};
  const post=(action:string,data:object)=>page.request.post('/api/v1/library/editor/'+action,{headers,data});
  const item=(await readLibrary()).entries.find((e:{simplified?:boolean;family:string})=>e.simplified&&e.family==='Synthetic_Truck');
  expect(item).toBeTruthy();
  expect(item.revision).toBe('r1');
  expect(item.profileId).toMatch(/^ecu-/);
  const open=async(key:string)=>await (await post('open',{instanceId:station.instanceId,key})).json();
  const first=await open(item.profileId);
  expect(first.declaration.states[0].dimensionsMm).toEqual([100.25,80,null]);
  expect(first.declaration.inspection).toMatchObject({template:'standard_pcb',overview:true,oblique:true,notes:'Fixture notes\nNot an executable recipe'});
  expect(first.document.geometry.per_physical_state).toEqual([]);
  expect(first.document.provenance_release.measurement_sources).toEqual([]);
  expect(first.document.inspection_workflows.recipes).toEqual([]);
  expect(first.document.metadata.status).toBe('DRAFT');
  await photos.getByRole('combobox',{name:'Photo category',exact:true}).selectOption('pcb_top');
  await photos.getByRole('combobox',{name:'Photo physical state',exact:true}).selectOption('pcb_top');
  await photos.getByLabel('Image file',{exact:true}).setInputFiles({name:'synthetic.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAABgAAAAQCAIAAACDRijCAAAANklEQVQ4Ea3BAQEAAAABIJZ33QlV5KHIQ5GHIg9FHoo8FHko8lDkochDkYciD0UeijwUeSjyMLa3F+G+cxutAAAAAElFTkSuQmCC','base64')});
  await photos.getByRole('button',{name:'Add photograph',exact:true}).click();
  await expect(editor).toContainText('Photo imported. Save the profile');
  await expect(photos.getByRole('button',{name:'Preview',exact:true})).toBeDisabled();
  await button('Save ECU profile').click();
  await expect(editor).toContainText('Profile saved in Core.');
  await photos.getByRole('button',{name:'Preview',exact:true}).click();
  const photo=photos.getByRole('img',{name:'Reference photograph',exact:true});
  await expect(photo).toBeVisible();
  await expect.poll(()=>photo.evaluate((node:HTMLImageElement)=>node.naturalWidth)).toBe(24);
  await photos.getByRole('button',{name:'Close preview',exact:true}).click();
  const saved=await open(item.profileId);
  expect(saved.declaration.photos[0]).toMatchObject({role:'pcb_top',stateId:'pcb_top',mime:'image/png'});
  // Dirty working copy survives a tab change; only explicit save commits it.
  const z=geo.getByRole('textbox',{name:'Height Z (mm)',exact:true});
  await z.fill('21.5');
  await page.getByRole('tab',{name:'System Status',exact:true}).click();
  await page.getByRole('tab',{name:'ECU Library',exact:true}).click();
  await expect(z).toHaveValue('21.5');
  expect((await open(item.profileId)).declaration.states[0].dimensionsMm[2]).toBeNull();
  await button('Save ECU profile').click();
  await expect(editor).toContainText('Profile saved in Core.');
  await button('Close editor').click();
  await library.getByRole('button',{name:'Browse Synthetic Truck 285 r1',exact:true}).click();
  await library.getByRole('tab',{name:'Saved profile',exact:true}).click();
  const viewer=library.getByRole('region',{name:'Saved profile viewer',exact:true});
  await viewer.getByRole('button',{name:'Preview saved profile',exact:true}).click();
  await expect(viewer).toContainText('100.25 × 80 × 21.5 mm');
  await expect(viewer).toContainText('TEST-OE-285');
  await library.getByRole('button',{name:'Open reference editor',exact:true}).click();
  await expect(editor).toContainText('Draft loaded from Core.');
  await expect(z).toHaveValue('21.5');
  await expect(button('Advanced editor')).toHaveCount(0);
  await button('Create next revision').click();
  await expect(editor).toContainText('New draft revision created.');
  await expect.poll(async()=> (await readLibrary()).entries.filter((e:{simplified?:boolean;family:string})=>e.simplified&&e.family==='Synthetic_Truck').map((e:{revision:string})=>e.revision).sort()).toEqual(['r1','r2']);
  await page.setViewportSize({width:390,height:844});
  expect(await editor.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
