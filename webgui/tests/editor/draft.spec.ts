import {expect,test} from '@playwright/test';
import {readFileSync} from 'node:fs';

test('actual ECU editor: operator creates, validates, saves, reloads and clones an unsigned draft',async({page})=>{
  const credentials=JSON.parse(readFileSync('../.station-test-auth.json','utf8'));
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('User name',{exact:true}).fill(credentials.username);
  await page.getByLabel('Password',{exact:true}).fill(credentials.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'System Status',exact:true})).toBeVisible();
  const identity=await (await page.request.get('/api/v1/auth/session')).json();
  expect(identity.role).toBe('operator');
  await page.locator('.desktop-icons').getByRole('button',{name:'ECU Library',exact:true}).click();
  const library=page.getByRole('dialog',{name:'ECU Library',exact:true});
  await library.getByRole('button',{name:'Browse ETC3 v1',exact:true}).click();
  await library.getByRole('button',{name:'Open reference editor',exact:true}).click();
  const editor=library.getByRole('region',{name:'ECU reference editor'});
  await editor.getByLabel('New profile ID',{exact:true}).fill('browser-etc3-draft');
  await editor.getByLabel('Revision',{exact:true}).fill('r1');
  await editor.getByLabel('Display name',{exact:true}).fill('Browser synthetic draft');
  await editor.getByRole('button',{name:'Create draft',exact:true}).click();
  await expect(editor).toContainText('Draft saved in Core.');
  await expect(editor).toContainText('DRAFT / NOT_READY');
  await editor.getByLabel('Section',{exact:true}).selectOption('identity');
  const area=editor.getByLabel('Declared identity (JSON)',{exact:true});
  const document=JSON.parse(await area.inputValue());
  document.manufacturer='Synthetic browser manufacturer';
  await area.fill(JSON.stringify(document,null,2));
  await editor.getByRole('button',{name:'Validate document',exact:true}).click();
  await expect(editor).toContainText('Valid structure · NOT_READY');
  await expect(editor).toContainText('profile is not approved V1');
  await editor.getByRole('button',{name:'Save draft generation',exact:true}).click();
  await expect(editor).toContainText('Draft saved in Core.');
  await expect(editor.getByRole('button',{name:'Save draft generation',exact:true})).toBeDisabled();
  await editor.getByRole('button',{name:'Reload latest',exact:true}).click();
  await expect(editor).toContainText('Draft loaded from Core.');
  expect(JSON.parse(await area.inputValue()).manufacturer).toBe('Synthetic browser manufacturer');

  // Two clients editing the same stored generation cannot overwrite it.
  const station=await (await page.request.get('/api/v1/station')).json();
  const headers={Origin:'http://127.0.0.1:18492','X-Vision-Client':'webgui'};
  const base='/api/v1/library/editor/';
  const opened=await (await page.request.post(base+'open',{headers,data:{instanceId:station.instanceId,key:'browser-etc3-draft'}})).json();
  opened.document.identity.aliases=['other-client'];
  const otherSave=await page.request.post(base+'save',{headers,data:{instanceId:station.instanceId,key:opened.key,etag:opened.etag,document:opened.document}});
  expect(otherSave.status()).toBe(200);
  document.manufacturer='stale local text';
  await area.fill(JSON.stringify(document,null,2));
  await editor.getByRole('button',{name:'Save draft generation',exact:true}).click();
  await expect(editor).toContainText('Core rejected this change');
  await expect(editor.getByRole('button',{name:'Save draft generation',exact:true})).toBeDisabled();
  page.once('dialog',dialog=>dialog.accept());
  await editor.getByRole('button',{name:'Reload latest',exact:true}).click();
  await expect(editor).toContainText('Draft loaded from Core.');
  expect(JSON.parse(await area.inputValue()).aliases).toEqual(['other-client']);

  await editor.getByLabel('New profile ID',{exact:true}).fill('browser-etc3-revision2');
  await editor.getByLabel('New revision',{exact:true}).fill('r2');
  await editor.getByRole('button',{name:'Clone saved revision',exact:true}).click();
  await expect(editor).toContainText('New draft revision created.');
  await editor.getByRole('button',{name:'Close editor',exact:true}).click();
  await expect(library.getByRole('button',{name:'Browse Browser synthetic draft r2',exact:true})).toBeVisible();
  await library.getByRole('button',{name:'Browse Browser synthetic draft r1',exact:true}).click();
  await library.getByRole('tab',{name:'Revision history (3)'}).click();
  await expect(library.getByRole('table',{name:'Reference revision history'}).locator('tbody tr')).toHaveCount(3);
  const after=await (await page.request.get('/api/v1/station')).json();
  expect(after).toMatchObject({instanceId:station.instanceId,state:'NO_ACTIVE_SESSION',coreConnection:'CONNECTED'});
  expect(errors).toEqual([]);
  expect(await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}))).not.toContain('Synthetic browser manufacturer');
});
